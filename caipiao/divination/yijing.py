def _build_hexagram_index() -> Dict[str, Hexagram]:
    """构建六十四卦索引."""
    index = {}
    for data in _HEXAGRAM_DATA:
        name, full_name, number, upper, lower, symbol, gua_ci, tuan_ci, xiang_ci, yao_ci, nature, desc = data
        h = Hexagram(
            name=name, full_name=full_name, number=number,
            upper=upper, lower=lower, symbol=symbol,
            gua_ci=gua_ci, tuan_ci=tuan_ci, xiang_ci=xiang_ci,
            yao_ci=yao_ci, nature=nature, description=desc,
        )
        index[name] = h
        index[full_name] = h
        index[number] = h
    return index



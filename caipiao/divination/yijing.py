def _build_full_index() -> Dict:
    """构建完整64卦索引."""
    index = {}

    for (upper_name, lower_name), data in _FULL_64_HEXAGRAMS.items():
        name, full_name, number, gua_ci, tuan_ci, xiang_ci, yao_ci, nature, desc = data
        h = Hexagram(
            name=name, full_name=full_name, number=number,
            upper=upper_name, lower=lower_name, symbol=f"䷀",
            gua_ci=gua_ci, tuan_ci=tuan_ci, xiang_ci=xiang_ci,
            yao_ci=yao_ci, nature=nature, description=desc,
        )
        index[name] = h
        index[full_name] = h
        index[number] = h
        index[(upper_name, lower_name)] = h

    return index



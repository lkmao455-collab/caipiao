    changed = []
    for y in yao:
        if y == 2:  # 老阳变少阴
            changed.append(0)
        elif y == 3:  # 老阴变少阳
            changed.append(1)
        else:
            changed.append(y)

    # 从变爻中提取上下卦
    lower_yao = tuple(changed[:3])
    upper_yao = tuple(changed[3:])

    lower_trigram = get_trigram_by_yao(lower_yao)
    upper_trigram = get_trigram_by_yao(upper_yao)

    if lower_trigram and upper_trigram:
        return get_hexagram(upper_trigram.name, lower_trigram.name)
    return None

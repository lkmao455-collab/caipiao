def get_yao_positions(yao: tuple[int, ...]) -> List[str]:
    """获取六爻位置描述.

    Args:
        yao: 6个爻的值 (从下到上，1=阳，0=阴，2=老阳变，3=老阴变)

    Returns:
        每爻的位置和性质描述
    """
    positions = ["初爻", "二爻", "三爻", "四爻", "五爻", "上爻"]
    result = []
    for i, (y, pos) in enumerate(zip(yao, positions)):
        if y in (1, 2):
            yao_type = "阳"
            line = "━━━━━"
        else:
            yao_type = "阴"
            line = "━ ━"
        if y in (2, 3):
            yao_type += "（变）"
        result.append(f"{pos}（{yao_type}）{line}")
    return result


